"""Private files (bank statements now; order documents later): stored in upload_dir/private, which
is NOT mounted as static files, and handed out only by endpoints that check the user's rights.

The file name on disk is generated by the server; the type is detected from the first bytes.
"""
import uuid
from pathlib import Path
from typing import BinaryIO

from app.config import settings
from app.services.errors import DomainError

CHUNK = 64 * 1024
STATEMENT_TYPES = {b"%PDF-": "pdf", b"\xff\xd8\xff": "jpg", b"\x89PNG\r\n\x1a\n": "png"}
MEDIA_TYPES = {"pdf": "application/pdf", "jpg": "image/jpeg", "png": "image/png"}


def private_root() -> Path:
    return Path(settings.upload_dir) / "private"


def absolute(relative_path: str) -> Path:
    """Resolve a stored path and make sure it stays inside the private folder."""
    path = (Path(settings.upload_dir) / relative_path).resolve()
    if not path.is_relative_to(private_root().resolve()):
        raise ValueError(f"Not a private file: {relative_path}")
    return path


def save_statement(payment_id: int, source: BinaryIO, filename: str | None) -> str:
    """Bank statement for a manual payment (form 4.6.3.1, field 10): PDF, JPG or PNG."""
    head = source.read(CHUNK)
    ext = next((e for sig, e in STATEMENT_TYPES.items() if head.startswith(sig)), None)
    if ext is None:
        raise DomainError(f"Файл «{filename or 'без назви'}»: виписка має бути PDF, JPG або PNG", 422)
    limit = settings.max_statement_mb * 1024 * 1024
    relative = f"private/statements/{payment_id}/{uuid.uuid4().hex}.{ext}"
    target = absolute(relative)
    target.parent.mkdir(parents=True, exist_ok=True)
    size = 0
    try:
        with target.open("wb") as out:
            chunk = head
            while chunk:
                size += len(chunk)
                if size > limit:
                    raise DomainError(f"Виписка більша за {settings.max_statement_mb} МБ", 413)
                out.write(chunk)
                chunk = source.read(CHUNK)
    except BaseException:
        target.unlink(missing_ok=True)
        raise
    return relative


def remove(relative_path: str | None) -> None:
    if relative_path:
        absolute(relative_path).unlink(missing_ok=True)
