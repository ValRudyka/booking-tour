"""Private files (bank statements, order documents, cancellation evidence): stored in
upload_dir/private, which is NOT mounted as static files, and handed out only by endpoints that
check the user's rights.

The file name on disk is generated by the server; the type is detected from the first bytes.
"""
import uuid
from pathlib import Path
from typing import BinaryIO

from app.config import settings
from app.services.errors import DomainError

CHUNK = 64 * 1024
PDF_JPG_PNG = {b"%PDF-": "pdf", b"\xff\xd8\xff": "jpg", b"\x89PNG\r\n\x1a\n": "png"}
PDF_JPG = {b"%PDF-": "pdf", b"\xff\xd8\xff": "jpg"}
STATEMENT_TYPES = PDF_JPG_PNG
MEDIA_TYPES = {"pdf": "application/pdf", "jpg": "image/jpeg", "png": "image/png"}


def private_root() -> Path:
    return Path(settings.upload_dir) / "private"


def absolute(relative_path: str) -> Path:
    """Resolve a stored path and make sure it stays inside the private folder."""
    path = (Path(settings.upload_dir) / relative_path).resolve()
    if not path.is_relative_to(private_root().resolve()):
        raise ValueError(f"Not a private file: {relative_path}")
    return path


def save_private(folder: str, source: BinaryIO, filename: str | None, *, allowed: dict[bytes, str],
                 max_mb: int, wrong_type: str, too_big: str) -> str:
    """Save an upload as private/<folder>/<random>.<ext>; returns the stored relative path.
    `wrong_type` / `too_big` are the Ukrainian messages ({name} = the client's file name)."""
    head = source.read(CHUNK)
    ext = next((e for sig, e in allowed.items() if head.startswith(sig)), None)
    name = filename or "без назви"
    if ext is None:
        raise DomainError(wrong_type.format(name=name), 422)
    limit = max_mb * 1024 * 1024
    relative = f"private/{folder}/{uuid.uuid4().hex}.{ext}"
    target = absolute(relative)
    target.parent.mkdir(parents=True, exist_ok=True)
    size = 0
    try:
        with target.open("wb") as out:
            chunk = head
            while chunk:
                size += len(chunk)
                if size > limit:
                    raise DomainError(too_big.format(name=name), 413)
                out.write(chunk)
                chunk = source.read(CHUNK)
    except BaseException:
        target.unlink(missing_ok=True)
        raise
    return relative


def save_statement(folder_id: int | str, source: BinaryIO, filename: str | None) -> str:
    """Bank statement / transfer receipt (form 4.6.3.1, field 10): PDF, JPG or PNG."""
    return save_private(f"statements/{folder_id}", source, filename, allowed=STATEMENT_TYPES,
                        max_mb=settings.max_statement_mb,
                        wrong_type="Файл «{name}»: виписка має бути PDF, JPG або PNG",
                        too_big=f"Виписка більша за {settings.max_statement_mb} МБ")


def media_type(relative_path: str) -> tuple[str, str]:
    """(extension, media type) of a stored file."""
    ext = Path(relative_path).suffix.lstrip(".")
    return ext, MEDIA_TYPES[ext]


def remove(relative_path: str | None) -> None:
    if relative_path:
        absolute(relative_path).unlink(missing_ok=True)
